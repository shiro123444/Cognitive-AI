/**
 * Translation resources for the `edufish` namespace.
 *
 * The adapter exports data only; the host owns i18next initialisation and
 * locale selection. Foundation keys and the keys used by result components
 * are flat camelCase strings. Nested groups at the end are compatibility
 * aliases for hosts that address historical dotted keys.
 */

export type EduFishUILocale = 'en-US' | 'zh-CN';

export type EduFishResourceValue =
  | string
  | { readonly [key: string]: EduFishResourceValue };

export interface EduFishUIResourceBundle {
  readonly edufish: Readonly<Record<string, EduFishResourceValue>>;
}

type TranslationShape<T> = T extends string
  ? string
  : { readonly [K in keyof T]: TranslationShape<T[K]> };

